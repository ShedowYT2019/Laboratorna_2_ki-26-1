#include <stdio.h> /// підключення бібліотек

int main(void) {
    double x = 2.5, y = 3.1, z = 0.41; /// вхідні данні 
    double S1 = 0; /// присвоєння змінної для відповіді
    double a = 0, b = 0, a1 = 0, c = 0, d = 0, b1 = 0; /// присвоєння змінних для обчислення
    
    a = x + z - 3 * z / x; /// проводемо обчислення для лівої частини формули
    b = 7 * z;

    a1 = a / b;

    c = 2*x + 12 * y - 3.5 * z / x; /// проведення обчислення для правої частини формули
    d = 3.5 * z;
    
    b1 = c / d;

    S1 = a1 + b1; /// проведення обчислення для знаходження відповіді

    printf("S1 = %lf\n", S1); /// виведення відповіді в термінал
    return 0; /// завершення програми Лаб 2
    
}